        // Textures, materials, seed and blobs are not part of it. Regenerate by copying the recipe's numbers here.
        private void ApplyRecipeAsset(TreePreset preset)
        {
            switch (preset)
            {
                case TreePreset.Oak:
                    ApplyOakAsset();
                    break;
                case TreePreset.Maple:
                    ApplyMapleAsset();
                    break;
                case TreePreset.Spruce:
                    ApplySpruceAsset();
                    break;
                case TreePreset.CottonCandy:
                    ApplyCottonCandyAsset();
                    break;
                case TreePreset.Twisted:
                    ApplyTwistedAsset();
                    break;
                case TreePreset.Hedge:
                case TreePreset.HedgeHigh:
                    ApplyHedgeAsset();
                    break;
                case TreePreset.Bush:
                    ApplyBushAsset();
                    break;
                case TreePreset.Fir:
                    ApplyFirAsset();
                    break;
                case TreePreset.Sapling:
                    ApplySaplingAsset();
                    break;
                case TreePreset.Cherry:
                    ApplySharedAssetTuning(preset);
                    CherryPuffs();
                    break;
                case TreePreset.Poplar:
                    ApplySharedAssetTuning(preset);
                    break;
            }
        }

